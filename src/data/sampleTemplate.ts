function spawnZone(name: string, player: string, layout: string): Zone {
  const mo: MainObject = {
    type: 'Spawn',
    spawn: player,
    placement: 'Center',
    buildingsConstructionSid: 'medium_buildings_construction',
  }
  return {
    name,
    size: 0.9,
    layout,
    mainObjects: [mo],
    zoneBiome: { type: 'MatchMainObject', args: ['0'] },
    contentBiome: { type: 'MatchMainObject', args: ['0'] },
    metaObjectsBiome: { type: 'MatchMainObject', args: ['0'] },
    roads: [
      {
        type: 'Stone',
        from: { type: 'MainObject', args: ['0'] },
        to: { type: 'Connection', args: [`${name}-Center`] },
      },
    ],
    mandatoryContent: ['group_spawn'],
    contentCountLimits: ['content_limits_spawn'],
    crossroadsPosition: 0,
    guardedContentValue: 0,
    guardedContentValuePerArea: 16000,
    unguardedContentValue: 0,
    unguardedContentValuePerArea: 2600,
    resourcesValue: 0,
    resourcesValuePerArea: 500,
    guardedContentPool: [
      'classic_template_pool_random_t2_item',
      'classic_template_pool_random_t2_unit_bank',
      'classic_template_pool_random_t2_hire',
    ],
    unguardedContentPool: ['classic_template_pool_random_unguarded_t2_base'],
    resourcesContentPool: ['content_pool_general_resources_start_zone_medium'],
    guardCutoffValue: 1200,
    guardMultiplier: 1.2,
    guardRandomization: 0.05,
    guardWeeklyIncrement: 0.1,
    guardReactionDistribution: [120, 60, 20, 10, 4, 0],
  }
}

function treasureZone(name: string, tier: 't2' | 't3', size: number): Zone {
  const guarded = tier === 't2' ? 70000 : 220000
  const multiplier = tier === 't2' ? 1 : 1.4
  return {
    name,
    size,
    layout: 'zone_layout_treasures',
    mainObjects: [],
    zoneBiome: { type: 'FromList', args: ['differentFrom: Spawn-A'] },
    contentBiome: { type: 'FromList', args: [] },
    metaObjectsBiome: { type: 'FromList', args: [] },
    roads: [],
    mandatoryContent: ['group_treasure'],
    contentCountLimits: ['content_limits_treasure'],
    crossroadsPosition: 0,
    guardedContentValue: guarded,
    guardedContentValuePerArea: 0,
    unguardedContentValue: tier === 't2' ? 9000 : 20000,
    unguardedContentValuePerArea: 0,
    resourcesValue: 8000,
    resourcesValuePerArea: 0,
    guardedContentPool: [
      tier === 't2'
        ? 'classic_template_pool_random_t2_item'
        : 'classic_template_pool_random_t3_item',
      tier === 't2'
        ? 'classic_template_pool_random_t2_unit_bank'
        : 'classic_template_pool_random_t3_unit_bank',
    ],
    unguardedContentPool: ['classic_template_pool_random_unguarded_t3_base'],
    resourcesContentPool: ['content_pool_general_resources_treasure_zone_medium'],
    guardCutoffValue: 1200,
    guardMultiplier: multiplier,
    guardRandomization: 0.05,
    guardWeeklyIncrement: 0.1,
    guardReactionDistribution: [40, 40, 20, 10, 4, 0],
  }
}

