/**
 * Формат записи JSON-файлов редактора (`.rmg.json` + sidecar `.editor.json`).
 *
 * Отступ — табуляция. Замер на эталонном шаблоне (3674 строки, вложенность до
 * 5 уровней): при двух пробелах файл весит 253 581 байт, при табах —
 * 194 415 (минус 59 КБ, −23%). Штатные шаблоны игры
 * (`StreamingAssets/map_templates/*.rmg.json`, все 60 файлов) набраны табами,
 * так что запись в том же стиле ещё и diff-friendly к оригиналу.
 *
 * Переводы строк — LF (игра пишет CRLF, но JSON это не различает, а файл
 * на байт короче на каждой строке). BOM нет, хвостовой перевод строки нет —
 * так же, как в штатных шаблонах.
 *
 * Порядок ключей не меняется: `JSON.stringify` сохраняет порядок вставки ключей,
 * т.е. порядок полей разобранного файла.
 */
export const JSON_INDENT = '\t'

/** Сериализация значения в JSON с игровым форматированием (табы вместо пробелов). */
export function stringifyJson(value: unknown): string {
  return JSON.stringify(value, null, JSON_INDENT)
}
